type I18nContextValue = {
  language: AppLanguage;
  setLanguage: (language: AppLanguage) => void;
  t: (key: string, replacements?: Record<string, string | number>) => string;
};

const I18nContext = createContext<I18nContextValue>({
  language: 'pt-BR',
  setLanguage: () => undefined,
  t: (key) => dictionaries['pt-BR'][key] ?? key,
});

export const I18nProvider = I18nContext.Provider;

export function normalizeLanguage(value: string | null | undefined): AppLanguage {
  if (value === 'en-US' || value?.toLowerCase().startsWith('en')) return 'en-US';
  if (value === 'es' || value?.toLowerCase().startsWith('es')) return 'es';
  return 'pt-BR';
}

export function createTranslator(language: AppLanguage) {
  return (key: string, replacements: Record<string, string | number> = {}) => {
    let text = dictionaries[language][key] ?? dictionaries['pt-BR'][key] ?? key;
    for (const [name, value] of Object.entries(replacements)) {
      text = text.replaceAll(`{${name}}`, String(value));
    }
    return text;
  };
}

export function useI18n() {
  return useContext(I18nContext);
}

export function genderLabel(value: GenderIdentity, t: I18nContextValue['t']) {
  return t(value);
}

export function sexualityLabel(value: Sexuality, t: I18nContextValue['t']) {
  return t(value);
}
